-- Trilha de capacitação: materiais de estudo (PDFs, vídeos e links) organizados por etapas.
CREATE TABLE materiais (
  id         INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  titulo     VARCHAR(150) NOT NULL,
  descricao  VARCHAR(500) NULL,
  tipo       ENUM('pdf', 'video', 'link') NOT NULL,
  url        VARCHAR(500) NOT NULL,
  etapa      VARCHAR(80)  NOT NULL,
  ordem      SMALLINT UNSIGNED NOT NULL DEFAULT 99,
  criado_por INT UNSIGNED NULL,
  criado_em  DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
  KEY idx_materiais_etapa (etapa, ordem),
  CONSTRAINT fk_materiais_criado_por FOREIGN KEY (criado_por) REFERENCES usuarios (id) ON DELETE SET NULL
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

